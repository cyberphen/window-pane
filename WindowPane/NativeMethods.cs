    public static IntPtr GetRootWindow(IntPtr hWnd)
    {
        if (hWnd == IntPtr.Zero) return IntPtr.Zero;
        var root = GetAncestor(hWnd, GA_ROOT);
        return root != IntPtr.Zero ? root : hWnd;
    }

    public static int NcHitTest(IntPtr hWnd, Point screenPt)
    {
        var lp = (IntPtr)((screenPt.Y << 16) | (screenPt.X & 0xFFFF));
        return unchecked((int)(long)SendMessage(hWnd, WM_NCHITTEST, IntPtr.Zero, lp));
    }

